#pragma once

/* Compile-only subset of ZMK v0.3.0 dt-bindings/zmk/keys.h. Tests assert the
 * emitted raw usages independently; firmware builds use the real header. */
#define TEST_KEY(id) ((0x07UL << 16) | (id))
#define RETURN TEST_KEY(0x28)
#define ESC TEST_KEY(0x29)
#define BSPC TEST_KEY(0x2a)
#define TAB TEST_KEY(0x2b)
#define SPACE TEST_KEY(0x2c)
#define MINUS TEST_KEY(0x2d)
#define SEMI TEST_KEY(0x33)
#define COLON ((0x02UL << 24) | TEST_KEY(0x33))
#define SQT TEST_KEY(0x34)
#define COMMA TEST_KEY(0x36)
#define DOT TEST_KEY(0x37)
#define EXCL ((0x02UL << 24) | TEST_KEY(0x1e))
#define AT ((0x02UL << 24) | TEST_KEY(0x1f))
#define HASH ((0x02UL << 24) | TEST_KEY(0x20))
#define DLLR ((0x02UL << 24) | TEST_KEY(0x21))
#define PRCNT ((0x02UL << 24) | TEST_KEY(0x22))
#define CARET ((0x02UL << 24) | TEST_KEY(0x23))
#define AMPS ((0x02UL << 24) | TEST_KEY(0x24))
#define STAR ((0x02UL << 24) | TEST_KEY(0x25))
#define LPAR ((0x02UL << 24) | TEST_KEY(0x26))
#define RPAR ((0x02UL << 24) | TEST_KEY(0x27))
#define UNDER ((0x02UL << 24) | TEST_KEY(0x2d))
#define EQUAL TEST_KEY(0x2e)
#define PLUS ((0x02UL << 24) | TEST_KEY(0x2e))
#define LBKT TEST_KEY(0x2f)
#define LBRC ((0x02UL << 24) | TEST_KEY(0x2f))
#define RBKT TEST_KEY(0x30)
#define RBRC ((0x02UL << 24) | TEST_KEY(0x30))
#define BSLH TEST_KEY(0x31)
#define TILDE ((0x02UL << 24) | TEST_KEY(0x35))
#define LT ((0x02UL << 24) | TEST_KEY(0x36))
#define GT ((0x02UL << 24) | TEST_KEY(0x37))
#define FSLH TEST_KEY(0x38)
#define HOME TEST_KEY(0x4a)
#define PAGE_UP TEST_KEY(0x4b)
#define END TEST_KEY(0x4d)
#define PAGE_DOWN TEST_KEY(0x4e)
#define RIGHT_ARROW TEST_KEY(0x4f)
#define LEFT_ARROW TEST_KEY(0x50)
#define DOWN_ARROW TEST_KEY(0x51)
#define UP_ARROW TEST_KEY(0x52)
#define LCTRL TEST_KEY(0xe0)
#define LSHFT TEST_KEY(0xe1)
#define LALT TEST_KEY(0xe2)
#define LGUI TEST_KEY(0xe3)
#define GLOBE ((0x0cUL << 16) | 0x29d)
